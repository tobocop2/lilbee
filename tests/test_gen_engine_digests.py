"""The digest table of the engine wheels is generated from the pack record."""

from __future__ import annotations

import ast
import importlib.util
import json
import runpy
import sys
from pathlib import Path
from types import ModuleType
from typing import Any

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
GENERATOR = REPO_ROOT / "tools" / "gen_engine_digests.py"
RECORD = REPO_ROOT / "tools" / "engine_packs.json"
SHIPPED = REPO_ROOT / "src" / "lilbee" / "providers" / "fleet" / "engine_digests.py"
FIXTURES = Path(__file__).parent / "fixtures" / "engine_digests"
PREFIX = "https://index.test/packs/"
TEI = "lilbee_engine_tei-1.9.4-1.cpu-py3-none-manylinux_2_34_x86_64.whl"
SHA = "a" * 64


@pytest.fixture(scope="module")
def gen() -> ModuleType:
    spec = importlib.util.spec_from_file_location("gen_engine_digests", GENERATOR)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def entry(name: str, sha: str = SHA, size: int = 1, url: str | None = None) -> dict[str, Any]:
    return {"file": name, "url": url or PREFIX + name, "sha256": sha, "size": size}


def parse(text: str) -> dict[str, Any]:
    tree = ast.parse(text)
    node = next(n.value for n in tree.body if isinstance(n, ast.Assign))
    table: dict[str, Any] = ast.literal_eval(node)
    return table


def table(gen: ModuleType, rows: list[dict[str, Any]]) -> dict[str, Any]:
    return parse(gen.render(rows))


def committed_record() -> list[dict[str, Any]]:
    record: list[dict[str, Any]] = json.loads(RECORD.read_text(encoding="utf-8"))
    return record


def shipped_rows() -> dict[str, dict[str, Any]]:
    """Map each asset url of the shipped table to its row."""
    return {
        row["url"]: row
        for versions in parse(SHIPPED.read_text(encoding="utf-8")).values()
        for cells in versions.values()
        for row in cells.values()
    }


def test_the_committed_record_renders_the_shipped_table(gen: ModuleType) -> None:
    record = committed_record()
    assert len(record) == 17
    assert gen.render(record) == SHIPPED.read_text(encoding="utf-8")


@pytest.mark.parametrize("asset", [row["file"] for row in committed_record()])
def test_a_shipped_row_equals_its_record_entry(gen: ModuleType, asset: str) -> None:
    entry_of = next(row for row in committed_record() if row["file"] == asset)
    shipped = shipped_rows()[entry_of["url"]]
    assert (shipped["sha256"], shipped["size"]) == (entry_of["sha256"], entry_of["size"])


def test_the_record_and_the_shipped_table_list_the_same_assets() -> None:
    record = committed_record()
    assert len({row["url"] for row in record}) == len(record)
    assert {row["url"] for row in record} == set(shipped_rows())
    assert {row["file"].split("-")[0] for row in record} == {
        "lilbee_engine_llama_cpp",
        "lilbee_engine_ik_llama_cpp",
        "lilbee_engine_mistral_rs",
        "lilbee_engine_tei",
    }


def test_a_changed_digest_or_size_in_the_record_changes_the_table(gen: ModuleType) -> None:
    shipped = SHIPPED.read_text(encoding="utf-8")
    for index in range(len(committed_record())):
        for field, value in (("sha256", "0" * 64), ("size", 1)):
            record = committed_record()
            assert record[index][field] != value
            record[index][field] = value
            assert gen.render(record) != shipped, (index, field)


def test_the_fixture_record_renders_the_committed_table(gen: ModuleType) -> None:
    record = json.loads((FIXTURES / "record.json").read_text(encoding="utf-8"))
    expected = (FIXTURES / "expected.py.txt").read_text(encoding="utf-8")
    assert gen.render(record) == expected
    assert expected.startswith('"""Pack digests of the engine wheels, generated by')


def test_the_shipped_table_has_the_header_of_the_generator(gen: ModuleType) -> None:
    assert SHIPPED.read_text(encoding="utf-8").startswith(gen.render([]).split("MANIFESTS =")[0])


def test_a_wheel_becomes_a_cell_of_its_engine(gen: ModuleType) -> None:
    assert table(gen, [entry(TEI, size=99)]) == {
        "tei": {
            "1.9.4": {
                "linux-x86_64-cpu": {
                    "sha256": SHA,
                    "url": PREFIX + TEI,
                    "size": 99,
                    "min_os": "2.34",
                }
            }
        }
    }


@pytest.mark.parametrize(
    ("tag", "cell", "floor"),
    [
        ("manylinux_2_28_x86_64", "linux-x86_64-cpu", "2.28"),
        ("manylinux_2_39_aarch64", "linux-aarch64-cpu", "2.39"),
        ("macosx_14_0_arm64", "macos-arm64-cpu", "14.0"),
        ("macosx_13_3_arm64", "macos-arm64-cpu", "13.3"),
        ("win_amd64", "windows-x86_64-cpu", None),
    ],
)
def test_the_platform_tag_gives_the_cell_and_the_floor(
    gen: ModuleType, tag: str, cell: str, floor: str | None
) -> None:
    name = f"lilbee_engine_tei-1.0-1.cpu-py3-none-{tag}.whl"
    got = table(gen, [entry(name)])["tei"]["1.0"]
    assert list(got) == [cell]
    assert got[cell]["min_os"] == floor


@pytest.mark.parametrize(
    ("slug", "engine"),
    [
        ("mistral_rs", "mistral.rs"),
        ("tei", "tei"),
        ("ik_llama_cpp", "ik_llama.cpp"),
        ("llama_cpp", "llama.cpp"),
    ],
)
def test_the_project_slug_gives_the_engine_name(gen: ModuleType, slug: str, engine: str) -> None:
    name = f"lilbee_engine_{slug}-1.0-1.cpu-py3-none-win_amd64.whl"
    assert list(table(gen, [entry(name)])) == [engine]


def test_a_wheel_without_an_engine_slug_is_refused(gen: ModuleType) -> None:
    name = "lilbee_engine-b12032-1.vulkan-py3-none-manylinux_2_34_x86_64.whl"
    with pytest.raises(gen.DigestError, match="wheel"):
        table(gen, [entry(name)])


def test_the_build_tag_gives_the_backend_with_dashes(gen: ModuleType) -> None:
    name = "lilbee_engine_llama_cpp-b1-1.cuda128_sm89-py3-none-win_amd64.whl"
    cells = table(gen, [entry(name)])["llama.cpp"]["b1"]
    assert list(cells) == ["windows-x86_64-cuda128-sm89"]
    assert cells["windows-x86_64-cuda128-sm89"]["sha256"] == SHA


def test_each_version_of_a_cell_keeps_its_own_digest_whatever_the_line_order(
    gen: ModuleType,
) -> None:
    newer = TEI.replace("1.9.4", "1.10.0")
    versions = table(gen, [entry(newer, "b" * 64, 2), entry(TEI)])["tei"]
    assert versions["1.9.4"]["linux-x86_64-cpu"]["sha256"] == SHA
    assert versions["1.10.0"]["linux-x86_64-cpu"]["sha256"] == "b" * 64


def test_an_ik_llama_version_with_a_commit_is_a_version_of_its_own(gen: ModuleType) -> None:
    one = "lilbee_engine_ik_llama_cpp-0+git13cffc006b82-1.cpu-py3-none-win_amd64.whl"
    two = one.replace("13cffc006b82", "0123456789ab")
    versions = table(gen, [entry(one), entry(two, "b" * 64)])
    assert sorted(versions["ik_llama.cpp"]) == ["0+git0123456789ab", "0+git13cffc006b82"]


def test_two_wheels_for_one_version_and_cell_are_refused(gen: ModuleType) -> None:
    rebuilt = TEI.replace("-1.cpu", "-2.cpu")
    with pytest.raises(gen.DigestError, match="already has a wheel"):
        table(gen, [entry(TEI), entry(rebuilt, "b" * 64)])


@pytest.mark.parametrize(
    ("row", "match"),
    [
        (entry("lilbee_engine_nope-1-1.cpu-py3-none-win_amd64.whl"), "engine"),
        (entry("lilbee_engine_tei-1-1.cpu-py3-none-plan9_mips.whl"), "platform"),
        (entry("lilbee_engine_tei-1-cpu-py3-none-win_amd64.whl"), "build tag"),
        (entry("lilbee_engine_tei-1.tar.gz"), "wheel"),
        (entry(TEI, "abc"), "sha256"),
        (entry(TEI, f"sha256:{SHA}"), "sha256"),
        (entry(TEI, SHA.upper()), "sha256"),
        (entry(TEI, size=0), "size"),
        (entry(TEI, url="http://index.test/packs/" + TEI), "https"),
        (entry(TEI, url="https://index.test/packs/other.whl"), "ends with the file"),
        ({k: v for k, v in entry(TEI).items() if k != "size"}, "no size"),
    ],
)
def test_an_input_the_table_cannot_state_is_refused(
    gen: ModuleType, row: dict[str, Any], match: str
) -> None:
    with pytest.raises(gen.DigestError, match=match):
        gen.render([row])


def test_the_table_records_the_release_base(gen: ModuleType) -> None:
    text = gen.render([])
    assert text.endswith('PACKAGES_URL = "https://github.com/tobocop2/lilbee/releases/download/"\n')


def test_the_command_writes_the_table_to_standard_output(
    capsys: pytest.CaptureFixture[str], monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setattr(sys, "argv", ["gen_engine_digests.py", str(FIXTURES / "record.json")])
    with pytest.raises(SystemExit) as done:
        runpy.run_path(str(GENERATOR), run_name="__main__")
    assert done.value.code == 0
    assert capsys.readouterr().out == (FIXTURES / "expected.py.txt").read_text(encoding="utf-8")


def test_the_command_needs_a_record(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(sys, "argv", ["gen_engine_digests.py"])
    with pytest.raises(SystemExit) as done:
        runpy.run_path(str(GENERATOR), run_name="__main__")
    assert done.value.code == 2


def test_the_command_reports_a_refused_input_and_exits_non_zero(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], monkeypatch: pytest.MonkeyPatch
) -> None:
    record = tmp_path / "r.json"
    record.write_text(json.dumps([entry(TEI, size=0)]), encoding="utf-8")
    monkeypatch.setattr(sys, "argv", ["g", str(record)])
    with pytest.raises(SystemExit) as done:
        runpy.run_path(str(GENERATOR), run_name="__main__")
    assert done.value.code == 1
    assert "no size" in capsys.readouterr().err
