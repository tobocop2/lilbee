"""The digest table of the engine wheels is generated from the engines index."""

from __future__ import annotations

import ast
import importlib.util
import json
import runpy
import sys
from pathlib import Path
from types import ModuleType

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
GENERATOR = REPO_ROOT / "tools" / "gen_engine_digests.py"
SHIPPED = REPO_ROOT / "src" / "lilbee" / "providers" / "fleet" / "engine_digests.py"
FIXTURES = Path(__file__).parent / "fixtures" / "engine_digests"
PREFIX = "https://index.test/packs/"
TEI = "lilbee_engine_tei-1.9.4-1.cpu-py3-none-manylinux_2_34_x86_64.whl"
SHA = "a" * 64


@pytest.fixture(scope="module")
def gen() -> ModuleType:
    spec = importlib.util.spec_from_file_location("gen_engine_digests", GENERATOR)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def table(gen: ModuleType, rows: list[tuple[str, str, int]], prefix: str = PREFIX) -> dict:
    packages = [{"filename": name, "hash": digest} for name, digest, _ in rows]
    sizes = {name: size for name, _, size in rows}
    tree = ast.parse(gen.render(packages, sizes, prefix))
    node = next(n.value for n in tree.body if isinstance(n, ast.Assign))
    return ast.literal_eval(node)


def test_the_fixture_inputs_render_the_committed_table(gen: ModuleType) -> None:
    packages = [
        json.loads(line)
        for line in (FIXTURES / "packages.json").read_text(encoding="utf-8").splitlines()
    ]
    sizes = json.loads((FIXTURES / "sizes.json").read_text(encoding="utf-8"))
    expected = (FIXTURES / "expected.py.txt").read_text(encoding="utf-8")
    assert gen.render(packages, sizes, PREFIX) == expected
    assert expected.startswith('"""Pack digests of the engine wheels, generated by')


def test_the_shipped_table_has_the_header_of_the_generator(gen: ModuleType) -> None:
    assert SHIPPED.read_text(encoding="utf-8").startswith(
        gen.render([], {}, PREFIX).split("MANIFESTS =")[0]
    )


def test_a_wheel_becomes_a_cell_of_its_engine(gen: ModuleType) -> None:
    assert table(gen, [(TEI, f"sha256={SHA}", 99)]) == {
        "tei": {
            "1.9.4": {
                "linux-x86_64-cpu": {
                    "sha256": SHA,
                    "url": PREFIX + TEI,
                    "size": 99,
                    "min_os": "2.34",
                }
            }
        }
    }


@pytest.mark.parametrize(
    ("tag", "cell", "floor"),
    [
        ("manylinux_2_28_x86_64", "linux-x86_64-cpu", "2.28"),
        ("manylinux_2_39_aarch64", "linux-aarch64-cpu", "2.39"),
        ("macosx_14_0_arm64", "macos-arm64-cpu", "14.0"),
        ("macosx_13_3_arm64", "macos-arm64-cpu", "13.3"),
        ("win_amd64", "windows-x86_64-cpu", None),
    ],
)
def test_the_platform_tag_gives_the_cell_and_the_floor(
    gen: ModuleType, tag: str, cell: str, floor: str | None
) -> None:
    name = f"lilbee_engine_tei-1.0-1.cpu-py3-none-{tag}.whl"
    got = table(gen, [(name, f"sha256={SHA}", 1)])["tei"]["1.0"]
    assert list(got) == [cell]
    assert got[cell]["min_os"] == floor


@pytest.mark.parametrize(
    ("slug", "engine"),
    [
        ("mistral_rs", "mistral.rs"),
        ("tei", "tei"),
        ("ik_llama_cpp", "ik_llama.cpp"),
        ("llama_cpp", "llama.cpp"),
    ],
)
def test_the_project_slug_gives_the_engine_name(gen: ModuleType, slug: str, engine: str) -> None:
    name = f"lilbee_engine_{slug}-1.0-1.cpu-py3-none-win_amd64.whl"
    assert list(table(gen, [(name, f"sha256={SHA}", 1)])) == [engine]


def test_a_wheel_without_an_engine_slug_is_refused(gen: ModuleType) -> None:
    name = "lilbee_engine-b12032-1.vulkan-py3-none-manylinux_2_34_x86_64.whl"
    with pytest.raises(gen.DigestError, match="wheel"):
        table(gen, [(name, f"sha256={SHA}", 5)])


def test_the_build_tag_gives_the_backend_with_dashes(gen: ModuleType) -> None:
    name = "lilbee_engine_llama_cpp-b1-1.cuda128_sm89-py3-none-win_amd64.whl"
    cells = table(gen, [(name, f"sha256:{SHA}", 1)])["llama.cpp"]["b1"]
    assert list(cells) == ["windows-x86_64-cuda128-sm89"]
    assert cells["windows-x86_64-cuda128-sm89"]["sha256"] == SHA


def test_a_prefix_without_a_slash_joins_the_file_name_with_one(gen: ModuleType) -> None:
    cells = table(gen, [(TEI, f"sha256={SHA}", 1)], "https://index.test/packs")["tei"]["1.9.4"]
    assert cells["linux-x86_64-cpu"]["url"] == PREFIX + TEI


def test_each_version_of_a_cell_keeps_its_own_digest_whatever_the_line_order(
    gen: ModuleType,
) -> None:
    newer = TEI.replace("1.9.4", "1.10.0")
    rows = [(newer, f"sha256={'b' * 64}", 2), (TEI, f"sha256={SHA}", 1)]
    versions = table(gen, rows)["tei"]
    assert versions["1.9.4"]["linux-x86_64-cpu"]["sha256"] == SHA
    assert versions["1.10.0"]["linux-x86_64-cpu"]["sha256"] == "b" * 64


def test_an_ik_llama_version_with_a_commit_is_a_version_of_its_own(gen: ModuleType) -> None:
    one = "lilbee_engine_ik_llama_cpp-0+git13cffc006b82-1.cpu-py3-none-win_amd64.whl"
    two = one.replace("13cffc006b82", "0123456789ab")
    versions = table(gen, [(one, f"sha256={SHA}", 1), (two, f"sha256={'b' * 64}", 1)])
    assert sorted(versions["ik_llama.cpp"]) == ["0+git0123456789ab", "0+git13cffc006b82"]


def test_two_wheels_for_one_version_and_cell_are_refused(gen: ModuleType) -> None:
    rebuilt = TEI.replace("-1.cpu", "-2.cpu")
    with pytest.raises(gen.DigestError, match="already has a wheel"):
        table(gen, [(TEI, f"sha256={SHA}", 1), (rebuilt, f"sha256={'b' * 64}", 1)])


@pytest.mark.parametrize(
    ("name", "digest", "size", "match"),
    [
        ("lilbee_engine_nope-1-1.cpu-py3-none-win_amd64.whl", f"sha256={SHA}", 1, "engine"),
        ("lilbee_engine_tei-1-1.cpu-py3-none-plan9_mips.whl", f"sha256={SHA}", 1, "platform"),
        ("lilbee_engine_tei-1-cpu-py3-none-win_amd64.whl", f"sha256={SHA}", 1, "build tag"),
        ("lilbee_engine_tei-1.tar.gz", f"sha256={SHA}", 1, "wheel"),
        (TEI, "sha256=abc", 1, "sha256"),
        (TEI, f"md5={SHA}", 1, "sha256"),
        (TEI, f"sha256={SHA}", 0, "size"),
    ],
)
def test_an_input_the_table_cannot_state_is_refused(
    gen: ModuleType, name: str, digest: str, size: int, match: str
) -> None:
    with pytest.raises(gen.DigestError, match=match):
        table(gen, [(name, digest, size)])


def test_a_wheel_without_a_size_is_refused(gen: ModuleType) -> None:
    with pytest.raises(gen.DigestError, match="no size"):
        gen.render([{"filename": TEI, "hash": f"sha256={SHA}"}], {}, PREFIX)


def test_the_command_writes_the_table_to_standard_output(
    capsys: pytest.CaptureFixture[str], monkeypatch: pytest.MonkeyPatch
) -> None:
    argv = [
        "gen_engine_digests.py",
        str(FIXTURES / "packages.json"),
        str(FIXTURES / "sizes.json"),
        "--packages-url",
        PREFIX,
    ]
    monkeypatch.setattr(sys, "argv", argv)
    with pytest.raises(SystemExit) as done:
        runpy.run_path(str(GENERATOR), run_name="__main__")
    assert done.value.code == 0
    assert capsys.readouterr().out == (FIXTURES / "expected.py.txt").read_text(encoding="utf-8")


def test_the_command_needs_a_packages_url(monkeypatch: pytest.MonkeyPatch) -> None:
    argv = ["gen_engine_digests.py", str(FIXTURES / "packages.json"), str(FIXTURES / "sizes.json")]
    monkeypatch.setattr(sys, "argv", argv)
    with pytest.raises(SystemExit) as done:
        runpy.run_path(str(GENERATOR), run_name="__main__")
    assert done.value.code == 2


def test_the_command_reports_a_refused_input_and_exits_non_zero(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], monkeypatch: pytest.MonkeyPatch
) -> None:
    packages = tmp_path / "p.json"
    packages.write_text(json.dumps({"filename": TEI, "hash": f"sha256={SHA}"}), encoding="utf-8")
    sizes = tmp_path / "s.json"
    sizes.write_text("{}", encoding="utf-8")
    monkeypatch.setattr(sys, "argv", ["g", str(packages), str(sizes), "--packages-url", PREFIX])
    with pytest.raises(SystemExit) as done:
        runpy.run_path(str(GENERATOR), run_name="__main__")
    assert done.value.code == 1
    assert "no size" in capsys.readouterr().err


@pytest.mark.parametrize(
    "prefix", ["http://index.test/packs/", "ftp://index.test/", "index.test/", ""]
)
def test_a_prefix_that_is_not_https_is_refused(gen: ModuleType, prefix: str) -> None:
    packages = [{"filename": TEI, "hash": f"sha256={SHA}"}]
    with pytest.raises(gen.DigestError, match="must start with https://"):
        gen.render(packages, {TEI: 1}, prefix)


def test_the_table_records_the_release_base_whatever_the_prefix(gen: ModuleType) -> None:
    text = gen.render([], {}, "https://index.test/packs")
    assert text.endswith('PACKAGES_URL = "https://github.com/tobocop2/lilbee/releases/download/"\n')


def test_a_package_url_replaces_the_prefix_for_that_wheel(gen: ModuleType) -> None:
    other = "https://index.test/other/" + TEI
    packages = [{"filename": TEI, "hash": f"sha256={SHA}", "url": other}]
    cell = table(gen, [(TEI, f"sha256={SHA}", 99)])["tei"]["1.9.4"]["linux-x86_64-cpu"]
    assert cell["url"] == PREFIX + TEI
    tree = ast.parse(gen.render(packages, {TEI: 99}, PREFIX))
    node = next(n.value for n in tree.body if isinstance(n, ast.Assign))
    assert ast.literal_eval(node)["tei"]["1.9.4"]["linux-x86_64-cpu"]["url"] == other


