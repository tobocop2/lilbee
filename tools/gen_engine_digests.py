"""Write the digest table of the engine wheels from the engines index inputs.

Usage: gen_engine_digests.py PACKAGES SIZES --packages-url PREFIX > engine_digests.py

PACKAGES is the JSON-lines input of the index (keys ``filename`` and ``hash``).
SIZES maps a file name to its size in bytes. PREFIX is the URL the wheels sit under.
A package may carry a ``url`` key, which replaces PREFIX plus the file name for that wheel.
The table always records ``PACKAGES_URL`` as the base that downloads must stay under.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

_ENGINES = {
    "mistral_rs": "mistral.rs",
    "tei": "tei",
    "ik_llama_cpp": "ik_llama.cpp",
    "llama_cpp": "llama.cpp",
    "mlx": "mlx",
}
_WHEEL = re.compile(
    r"lilbee_engine_(?P<slug>[a-z0-9_]+)-(?P<version>[^-]+)-(?P<build>[^-]+)"
    r"-[^-]+-[^-]+-(?P<platform>[^-]+)\.whl"
)
_BUILD = re.compile(r"\d+\.(?P<backend>[a-z0-9_]+)")
_MANYLINUX = re.compile(r"manylinux_2_(?P<minor>\d+)_(?P<arch>x86_64|aarch64)")
_MACOS = re.compile(r"macosx_(?P<major>\d+)_(?P<minor>\d+)_(?P<arch>arm64)")
_DIGEST = re.compile(r"sha256[=:](?P<hex>[0-9a-fA-F]{64})")
PACKAGES_URL = "https://github.com/tobocop2/lilbee/releases/download/"
_HEADER = (
    '"""Pack digests of the engine wheels, generated by tools/gen_engine_digests.py. '
    'Do not edit."""\n\n'
    "from __future__ import annotations\n\n"
    "from collections.abc import Mapping\n"
    "from typing import Any\n\n"
    "MANIFESTS: Mapping[str, Mapping[str, Mapping[str, Mapping[str, Any]]]]\n"
)


class DigestError(Exception):
    """An input of the generator cannot be stated in the table."""


def _host(name: str, platform: str) -> tuple[str, str, str | None]:
    if platform == "win_amd64":
        return "windows", "x86_64", None
    if found := _MANYLINUX.fullmatch(platform):
        return "linux", found["arch"], f"2.{found['minor']}"
    if found := _MACOS.fullmatch(platform):
        return "macos", found["arch"], f"{found['major']}.{found['minor']}"
    raise DigestError(f"{name}: the platform tag {platform!r} is not one an engine ships for.")


def _cell(
    name: str, size: int | None, digest: str, url: str
) -> tuple[str, str, str, dict[str, Any]]:
    wheel = _WHEEL.fullmatch(name)
    if wheel is None:
        raise DigestError(f"{name}: not the file name of an engine wheel.")
    engine = _ENGINES.get(wheel["slug"])
    if engine is None:
        raise DigestError(f"{name}: {wheel['slug']!r} is not an engine project.")
    build = _BUILD.fullmatch(wheel["build"])
    if build is None:
        raise DigestError(f"{name}: the build tag {wheel['build']!r} names no backend.")
    if size is None or size <= 0:
        raise DigestError(f"{name}: no size, or a size that is not a positive number.")
    found = _DIGEST.fullmatch(digest)
    if found is None:
        raise DigestError(f"{name}: the hash {digest!r} is not sha256 with 64 hex digits.")
    os_name, arch, min_os = _host(name, wheel["platform"])
    key = f"{os_name}-{arch}-{build['backend'].replace('_', '-')}"
    row = {"sha256": found["hex"].lower(), "url": url, "size": size, "min_os": min_os}
    return engine, wheel["version"], key, row


def _literal(value: Any, depth: int) -> str:
    pad = "    " * (depth + 1)
    if isinstance(value, dict):
        if not value:
            return "{}"
        lines = [f"{pad}{json.dumps(k)}: {_literal(v, depth + 1)}," for k, v in value.items()]
        return "{\n" + "\n".join(lines) + "\n" + "    " * depth + "}"
    return "None" if value is None else json.dumps(value)


def render(packages: list[dict[str, str]], sizes: dict[str, int], packages_url: str) -> str:
    """The text of the generated module: a row per engine, version and cell."""
    if not packages_url.startswith("https://"):
        raise DigestError(
            f"The packages url {packages_url!r} must start with https://. "
            "The table downloads engine wheels from it."
        )
    prefix = packages_url if packages_url.endswith("/") else packages_url + "/"
    table: dict[str, dict[str, dict[str, Any]]] = {}
    for entry in packages:
        name = entry["filename"]
        url = entry.get("url") or prefix + name
        engine, version, key, row = _cell(name, sizes.get(name), entry["hash"], url)
        cells = table.setdefault(engine, {}).setdefault(version, {})
        if key in cells:
            raise DigestError(f"{name}: {engine} {version} already has a wheel for {key}.")
        cells[key] = row
    ordered = {
        engine: {
            version: dict(sorted(cells.items())) for version, cells in sorted(versions.items())
        }
        for engine, versions in sorted(table.items())
    }
    base = json.dumps(PACKAGES_URL)
    return f"{_HEADER}MANIFESTS = {_literal(ordered, 0)}\nPACKAGES_URL = {base}\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("packages", type=Path)
    parser.add_argument("sizes", type=Path)
    parser.add_argument("--packages-url", required=True)
    args = parser.parse_args()
    lines = args.packages.read_text(encoding="utf-8").splitlines()
    packages = [json.loads(line) for line in lines if line.strip()]
    sizes = json.loads(args.sizes.read_text(encoding="utf-8"))
    try:
        sys.stdout.write(render(packages, sizes, args.packages_url))
    except DigestError as error:
        print(error, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
